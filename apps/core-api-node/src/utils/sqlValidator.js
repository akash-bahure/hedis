/**
 * SQL Validator Utility
 *
 * Enforces strict read-only safety for Text-to-SQL execution.
 * Allows SELECT and WITH SELECT queries only.
 * Rejects UPDATE, DELETE, DROP, ALTER, INSERT, CREATE, TRUNCATE, or any unsafe SQL operations.
 */

// List of forbidden SQL command keywords / patterns
const FORBIDDEN_KEYWORDS = [
  "INSERT",
  "UPDATE",
  "DELETE",
  "DROP",
  "ALTER",
  "CREATE",
  "TRUNCATE",
  "GRANT",
  "REVOKE",
  "RENAME",
  "REPLACE",
  "EXEC",
  "EXECUTE",
  "CALL",
  "COPY",
  "PG_SLEEP",
  "SHUTDOWN",
  "VACUUM",
  "REINDEX",
  "EXPLAIN",
  "PG_READ_FILE",
  "PG_LS_DIR",
  "INTO OUTFILE",
  "INTO DUMPFILE",
  "INFORMATION_SCHEMA",
  "PG_CATALOG",
  "PG_USER",
  "PG_AUTHID",
  "PG_SHADOW",
  "PG_SETTINGS",
  "SESSION_USER",
  "CURRENT_USER",
  "SYSTEM_USER",
];

const FORBIDDEN_PATTERNS = [
  /--/g,               // Single-line comment indicator
  /\/\*/g,             // Multi-line comment open
  /\*\//g,             // Multi-line comment close
  /;\s*$/g             // Semicolons are stripped from end but blocked inside
];

/**
 * Validates generated SQL string for safety and read-only compliance.
 *
 * @param {string} sql - Raw SQL string generated by LLM
 * @returns {{ valid: boolean, sql: string, error?: string }}
 */
function validateSql(sql) {
  if (!sql || typeof sql !== "string") {
    return { valid: false, sql: "", error: "SQL query is empty or invalid type." };
  }

  // DOS Protection: limit query length
  if (sql.length > 5000) {
    return { valid: false, sql: "", error: "SQL query exceeds maximum allowed length of 5000 characters." };
  }

  // Clean Markdown formatting (e.g., ```sql ... ```)
  let cleanSql = sql
    .replace(/```(?:sql|json)?/gi, "")
    .replace(/```/g, "")
    .trim();

  // Remove trailing semicolons (we strip them so we can execute single statements safely)
  cleanSql = cleanSql.replace(/;+\s*$/, "").trim();

  if (!cleanSql) {
    return { valid: false, sql: "", error: "Cleaned SQL query is empty." };
  }

  // Check for forbidden syntax patterns (comments, inline statements)
  for (const pattern of FORBIDDEN_PATTERNS) {
    if (pattern.test(cleanSql)) {
      return {
        valid: false,
        sql: cleanSql,
        error: "SQL comments (-- or /* */) and inline semicolons are strictly prohibited.",
      };
    }
  }

  const upperSql = cleanSql.toUpperCase();

  // Check that query starts with SELECT or WITH
  const startsWithSelectOrWith = /^(SELECT|WITH)\b/.test(upperSql);
  if (!startsWithSelectOrWith) {
    return {
      valid: false,
      sql: cleanSql,
      error: "Query must begin with SELECT or WITH (read-only queries only).",
    };
  }

  // Check for forbidden SQL keywords (ensuring keyword boundary)
  for (const forbidden of FORBIDDEN_KEYWORDS) {
    const regex = new RegExp(`\\b${forbidden}\\b`, "i");
    if (regex.test(cleanSql)) {
      return {
        valid: false,
        sql: cleanSql,
        error: `Unsafe SQL keyword or system table reference detected: '${forbidden}'. Only read-only SELECT queries on application schema tables are allowed.`,
      };
    }
  }

  // Check for SQL Injection patterns specifically (like UNION SELECT injection tricks)
  const unionInjectionRegex = /\bUNION\b\s+(All\s+)?\bSELECT\b/i;
  if (unionInjectionRegex.test(cleanSql)) {
    return {
      valid: false,
      sql: cleanSql,
      error: "UNION SELECT queries are blocked to prevent data-exfiltration/joining unauthorised system views.",
    };
  }

  return {
    valid: true,
    sql: cleanSql,
  };
}

module.exports = {
  validateSql,
  FORBIDDEN_KEYWORDS,
  FORBIDDEN_PATTERNS,
};
